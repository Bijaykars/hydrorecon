/** True on the boundary as well as inside it. */
export function inNepal(lat: number, lon: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return false;
  if (lat < 26.35 || lat > 30.4 || lon < 80.04 || lon > 88.17) return false;

  let inside = false;
  for (let i = 0, j = NEPAL.length - 1; i < NEPAL.length; j = i++) {
    const [xi, yi] = NEPAL[i];
    const [xj, yj] = NEPAL[j];
    const cross = (lon - xi) * (yj - yi) - (lat - yi) * (xj - xi);
    const on =
      Math.abs(cross) < 1e-10 &&
      lon >= Math.min(xi, xj) && lon <= Math.max(xi, xj) &&
      lat >= Math.min(yi, yj) && lat <= Math.max(yi, yj);
    if (on) return true;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

export const regionFor = (lat: number, lon: number): RegionMode =>
  inNepal(lat, lon) ? 'nepal' : 'global';

/**
 * Straight-line screening distance to the Natural Earth outline, km.
 * This lets the UI warn instead of pretending a generalized cartographic
 * boundary can settle jurisdiction close to an international border.
 */
export function distanceToNepalBoundaryKm(lat: number, lon: number): number {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return Infinity;
  const cos = Math.cos((lat * Math.PI) / 180) || 1;
  let best = Infinity;
  for (let i = 0; i + 1 < NEPAL.length; i++) {
    const [ax, ay] = NEPAL[i];
    const [bx, by] = NEPAL[i + 1];
    const px = (lon - ax) * cos;
    const py = lat - ay;
    const dx = (bx - ax) * cos;
    const dy = by - ay;
    const len2 = dx * dx + dy * dy;
    const t = len2 > 0 ? Math.max(0, Math.min(1, (px * dx + py * dy) / len2)) : 0;
    best = Math.min(best, Math.hypot(px - t * dx, py - t * dy) * 111.32);
  }
  return best;
}
